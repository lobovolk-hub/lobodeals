export function validatePsdealsBlock4Map({ existing_paths: existingPaths = [] } = {}) {
  const errors = []
  const ids = new Set()
  const availablePaths = new Set(existingPaths)
  for (const [index, entry] of PSDEALS_BLOCK4_CAPABILITIES.entries()) {
    if (!entry?.id || ids.has(entry.id)) errors.push(`block4_capability_id_invalid:${index}`)
    ids.add(entry.id)
    if (!PSDEALS_BLOCK4_STATUSES.includes(entry.status)) {
      errors.push(`block4_capability_status_invalid:${entry.id}`)
    }
    for (const file of entry.files) {
      if (!availablePaths.has(file)) errors.push(`block4_capability_file_missing:${entry.id}:${file}`)
    }
    for (const field of ['input', 'output', 'idempotency', 'retry_policy', 'safety_gate']) {
      if (typeof entry[field] !== 'string' || !entry[field].trim()) {
        errors.push(`block4_capability_contract_missing:${entry.id}:${field}`)
      }
    }
    if (!Array.isArray(entry.tests) || entry.tests.length === 0) {
      errors.push(`block4_capability_tests_missing:${entry.id}`)
    }
  }
  const statusCounts = Object.fromEntries(
    PSDEALS_BLOCK4_STATUSES.map((status) => [
      status,
      PSDEALS_BLOCK4_CAPABILITIES.filter((entry) => entry.status === status).length,
    ])
  )
  return {
    map_version: PSDEALS_BLOCK4_MAP_VERSION,
    valid: errors.length === 0,
    errors,
    capability_count: PSDEALS_BLOCK4_CAPABILITIES.length,
    status_counts: statusCounts,
    executes_commands: false,
    opens_connections: false,
    authorizes_operations: false,
  }
}
